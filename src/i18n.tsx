export type TKey = keyof Dict;
const DICTS: Record<Lang, Dict> = { ru, az };

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('family-tree:lang');
    if (saved === 'ru' || saved === 'az') return saved;
  } catch {
    /* storage may be unavailable */
  }
  return navigator.language?.startsWith('az') ? 'az' : 'ru';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang: (l) => {
        setLangState(l);
        document.documentElement.lang = l;
        try {
          localStorage.setItem('family-tree:lang', l);
        } catch {
          /* ignore */
        }
      },
      t: (k) => DICTS[lang][k],
    }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside provider');
  return v;
}
